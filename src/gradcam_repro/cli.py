def command_train(args: argparse.Namespace) -> None:
    config = TrainConfig(
        train_size=args.train_size,
        val_size=args.val_size,
        test_size=args.test_size,
        batch_size=args.batch_size,
        epochs=args.epochs,
        eval_every_steps=args.eval_every_steps,
        early_stop_acc=args.early_stop_acc,
        lr=args.lr,
        weight_decay=args.weight_decay,
        seed=args.seed,
    )
    result = train_model(args.output, config=config, device_name=args.device)
    print(json.dumps(result, indent=2))


def command_demo(args: argparse.Namespace) -> None:
    device = resolve_device(args.device)
    model = load_model(args.checkpoint, device)
    dataset = CrossHalfDataset(args.samples, seed=args.seed)
    detail_sample_idx = next(
        (idx for idx in range(len(dataset)) if int(dataset[idx]["label"]) == 1),
        0,
    )
    args.output_dir.mkdir(parents=True, exist_ok=True)
    method_grid = args.output_dir / "method_grid.png"
    class_discriminability = args.output_dir / "class_discriminability.png"
    notgradcam_decomposition = args.output_dir / "notgradcam_decomposition.png"
    detail_figures = {
        method_name: args.output_dir / f"{method_name}_decomposition.png"
        for method_name in DETAIL_RENDERERS
    }
    render_method_grid(
        model,
        dataset,
        output=method_grid,
        device=device,
        sample_count=args.samples,
    )
    render_class_discriminability(
        model,
        dataset,
        output=class_discriminability,
        device=device,
        sample_idx=0,
    )
    render_notgradcam_decomposition(
        model,
        dataset,
        output=notgradcam_decomposition,
        device=device,
        sample_idx=detail_sample_idx,
    )
    for method_name, output_path in detail_figures.items():
        DETAIL_RENDERERS[method_name](
            model,
            dataset,
            output=output_path,
            device=device,
            sample_idx=detail_sample_idx,
        )
    manifest = write_figure_manifest(
        output_dir=args.output_dir,
        checkpoint=args.checkpoint,
        figures={
            "method_grid": method_grid,
            "class_discriminability": class_discriminability,
            "notgradcam_decomposition": notgradcam_decomposition,
            **{f"{name}_decomposition": path for name, path in detail_figures.items()},
        },
        samples=args.samples,
        seed=args.seed,
        device=args.device,
        detail_sample_idx=detail_sample_idx,
    )
    print(
        json.dumps(
            {
                "method_grid": str(method_grid),
                "class_discriminability": str(class_discriminability),
                "notgradcam_decomposition": str(notgradcam_decomposition),
                "detail_figures": {name: str(path) for name, path in detail_figures.items()},
                "detail_sample_idx": detail_sample_idx,
                "manifest": str(manifest),
            },
            indent=2,
        )
    )


def command_score(args: argparse.Namespace) -> None:
    device = resolve_device(args.device)
    model = load_model(args.checkpoint, device)
    dataset = CrossHalfDataset(args.samples, seed=args.seed)
    scores = score_attributions(model, dataset, device)
    save_scores(scores, args.output)
    print(json.dumps({"scores": str(args.output), "summary": scores}, indent=2))


def command_deck(args: argparse.Namespace) -> None:
    repo_root = Path(__file__).resolve().parents[2]
    script = repo_root / "deck" / "build.mjs"
    node = args.node
    if not node.exists():
        raise SystemExit(f"Node runtime not found: {node}")
    result = subprocess.run([str(node), str(script)], cwd=repo_root, check=False)
    raise SystemExit(result.returncode)


