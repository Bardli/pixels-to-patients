def command_real_demo(args: argparse.Namespace) -> None:
    device = resolve_device(args.device)
    model = load_real_ct_model(args.checkpoint, device)
    dataset = RealCtDataset(args.data, split=args.split, limit=args.samples, positive_only=True)
    score_dataset = RealCtDataset(args.data, split=args.split, limit=args.score_samples, positive_only=True)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    grid_path = args.output_dir / "real_ct_method_grid.png"
    case_path = args.output_dir / "real_ct_single_case.png"
    render_real_ct_grid(
        model=model,
        dataset=dataset,
        output=grid_path,
        device=device,
        sample_count=args.samples,
        methods=args.methods,
    )
    render_real_ct_single_case(
        model=model,
        dataset=dataset,
        output=case_path,
        device=device,
        sample_idx=0,
        methods=args.methods,
    )
    scores = score_real_ct_attributions(
        model=model,
        dataset=score_dataset,
        device=device,
        methods=args.methods,
    )
    save_scores(scores, args.score_output)
    print(
        json.dumps(
            {
                "grid": str(grid_path),
                "single_case": str(case_path),
                "scores": str(args.score_output),
                "summary": scores,
            },
            indent=2,
        )
    )


