def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def format_manifest_path(path: Path) -> str:
    resolved = path.resolve()
    try:
        return str(resolved.relative_to(Path.cwd().resolve()))
    except ValueError:
        return str(resolved)


def write_figure_manifest(
    output_dir: Path,
    checkpoint: Path,
    figures: dict[str, Path],
    samples: int,
    seed: int,
    device: str,
    detail_sample_idx: int,
) -> Path:
    output_manifest_path = output_dir / "manifest.json"
    checkpoint = checkpoint.resolve()
    payload = {
        "schema": "gradcam-repro.figure-manifest.v1",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generated_by": "uv run gradcam-repro demo",
        "experiment": "toy_1voxel_3axis_cross_box_distractors_gradcam",
        "checkpoint": {
            "path": str(checkpoint),
            "sha256": sha256_file(checkpoint),
        },
        "parameters": {
            "samples": samples,
            "seed": seed,
            "device": device,
            "detail_sample_idx": detail_sample_idx,
        },
        "policy": "Deck image assets must be generated by experiment code and listed in this manifest.",
        "figures": [
            {
                "name": name,
                "path": format_manifest_path(path),
                "sha256": sha256_file(path),
                "source": "src/gradcam_repro/visualize.py",
            }
            for name, path in figures.items()
        ],
    }
    output_manifest_path.write_text(json.dumps(payload, indent=2))
    return output_manifest_path


